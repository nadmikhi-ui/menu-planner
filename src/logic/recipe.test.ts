import { describe, expect, it } from 'vitest';
import { productFromLine, productsFromRecipe, splitRecipeLine } from './recipe';

describe('productFromLine', () => {
  it.each([
    ['Филе индейки (сырое) — 80 г', 'индейка филе'],
    ['Свёкла (сырая) — 80 г', 'свекла'],
    ['Яйца — 2 шт. (180 г)', 'яйца'],
    ['Лимонный сок — 5 г (1 ч. л.)', 'лимон'],
    ['Оливковое масло — 5 г (1 ч. л.)', 'масло оливковое'],
    ['Специи: соль — 2 г', 'соль'],
    ['перец чёрный — 0,5 г', 'перец черный молотый'],
    ['Хлеб цельнозерновой — 30 г (1 ломтик)', 'хлеб цельнозерновой'],
    ['Гречка (сухая) — 60 г', 'гречка'],
    ['Укроп - 5 г', 'укроп'],
    ['Вода — 200 мл', ''],
    ['Кинза по вкусу', 'кинза'],
    ['Брынза или фета — 40 г', 'брынза'],
    ['Петрушка/кинза — 5 г', 'петрушка'],
    ['перец — по вкусу', 'перец черный молотый'],
    ['Грецкий орех10 г', 'грецкий орех'],
    ['Микс салата — 80 г', 'салат листовой'],
  ])('%s → %s', (line, product) => {
    expect(productFromLine(line)).toBe(product);
  });
});

describe('splitRecipeLine', () => {
  it('splits on commas but not inside parentheses or numbers', () => {
    expect(splitRecipeLine('Яйца — 2 шт. (180 г), Филе индейки (сырое, без кожи) — 80 г, перец — 0,5 г')).toEqual([
      'Яйца — 2 шт. (180 г)',
      'Филе индейки (сырое, без кожи) — 80 г',
      'перец — 0,5 г',
    ]);
  });
});

describe('productsFromRecipe', () => {
  it('collects unique products from all lines', () => {
    expect(
      productsFromRecipe([
        'Яйца — 2 шт. (180 г), Филе индейки (сырое) — 80 г',
        'Специи: соль — 2 г, перец чёрный — 0,5 г, орегано — 0,5 г',
        'Яйцо — 1 шт.',
      ]),
    ).toEqual(['яйца', 'индейка филе', 'соль', 'перец черный молотый', 'орегано']);
  });
});
