/** Words that describe a product state rather than the product itself: «Свёкла (сырая)», «вареная». */
const STATE_WORDS =
  /(?<!\p{L})(сыр(ая|ое|ой|ые)|сырых|вар[её]н(ая|ое|ый|ые)|отварн(ая|ое|ой|ые)|свеж(ая|ее|ий|ие)|готов(ая|ое|ый|ые)|охлажд[её]нн(ая|ое|ый|ые)|заморож[её]нн(ая|ое|ый|ые)|сух(ая|ое|ой|ие)|в сухом виде|без кожи|без костей|по вкусу|для подачи|по желанию|опционально)(?!\p{L})/giu;

/**
 * «Филе индейки (сырое) — 80 г» → «индейка филе»; «Специи: соль — 2 г» → «соль».
 * Returns '' for lines that are not a product to buy (вода, a heading).
 */
export function productFromLine(line: string): string {
  let s = line
    .replace(/^\s*(?:[•·✓\-–—]\s*)?/, '')
    .replace(/^\s*(?:специи|для соуса|для заправки|для подачи|соус|заправка|топпинг|маринад)\s*:\s*/iu, '')
    .replace(/\([^)]*\)?/g, ' ')
    .replace(/\[[^\]]*\]/g, ' ');
  // Cut at the amount: «— 80 г», «- 2 шт», «: 1 ч. л.», «80 г».
  s = s.split(/\s+[—–-]\s*|\s*:\s*|\s+\d|\s+½|\s+¼|\s+(?:щепотка|щепоть|пучок|горсть|ломтик|по вкусу)(?!\p{L})/iu)[0] ?? '';
  // «Брынза или фета», «петрушка/кинза» → the first option; «орех10 г» → «орех».
  s = s.split(/\s+или\s+|\s+либо\s+|\//iu)[0] ?? '';
  s = s.replace(/\d.*$/u, '').replace(/[—–]+$/u, '');
  s = s.replace(STATE_WORDS, ' ').replace(/[.,;:!]+$/u, '');
  const name = normalizeProductName(s).replace(/\s+/g, ' ').trim();
  if (!name || name.length < 2 || /^\d/.test(name)) return '';
  return name in PRODUCT_ALIASES ? PRODUCT_ALIASES[name]! : name;
}

/**
 * A recipe line may list several products: «Яйца — 2 шт. (180 г), Филе индейки — 80 г».
 * Splits on commas that are not inside parentheses or numbers («0,5 г»).
 */
export function splitRecipeLine(line: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let current = '';
  for (let i = 0; i < line.length; i++) {
    const ch = line[i]!;
    if (ch === '(') depth++;
    if (ch === ')') depth = Math.max(0, depth - 1);
    const isNumberComma = ch === ',' && /\d/.test(line[i - 1] ?? '') && /\d/.test(line[i + 1] ?? '');
    if ((ch === ',' || ch === ';') && depth === 0 && !isNumberComma) {
      parts.push(current);
      current = '';
    } else {
      current += ch;
    }
  }
  parts.push(current);
  return parts.map((p) => p.trim()).filter(Boolean);
}

/** Product names (normalized, no duplicates) for all lines of a recipe. */
export function productsFromRecipe(lines: string[]): string[] {
  return uniqueProducts(lines.flatMap(splitRecipeLine).map(productFromLine).filter(Boolean));
}
