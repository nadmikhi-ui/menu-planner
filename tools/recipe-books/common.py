import re

BOOKS = {
    'b': 'Книга завтраков (А. Маковецкий)',
    'l': 'Книга обедов (А. Маковецкий)',
    'd': 'Книга ужинов (А. Маковецкий)',
}

FISH = r'рыб|лосос|семг|сёмг|форел|треск|минта|хек|тунец|тунц|скумбри|сельд(?!ер)|сардин|дорадо|сибас|кревет|кальмар|мидии|морепродукт|судак|пангасиус|тилапи|горбуш|(?<![а-яё])кет[аы]|навага|окун|камбал'
POULTRY = r'кур[иі]|курин|индей|цыпл|утк|бедр'
MEAT = r'говяд|телят|свин|барани|ягнят|фарш|бекон|ветчин|колбас|тефтел'


def protein_of(text):
    t = text.lower()
    if re.search(FISH, t):
        return 'fish'
    if re.search(POULTRY, t):
        return 'poultry'
    if re.search(MEAT, t):
        return 'meat'
    return 'other'


